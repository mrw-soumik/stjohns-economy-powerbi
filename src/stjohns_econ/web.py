"""Bundle the processed data and the report specification for the web version.

Writes two small JavaScript files that assign globals, so docs/index.html works
from GitHub Pages and also when opened straight from disk (no fetch calls):
  docs/data/dashboard.js    window.DASHBOARD (geographies, indicators, series)
  docs/data/report-spec.js  window.REPORT_SPEC (pages and visuals)
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from . import report_spec as rs
from .paths import DOCS_DIR, PROCESSED_DIR, RAW_DIR

WEB_DATA_DIR = DOCS_DIR / "data"


def _read(name: str) -> pd.DataFrame:
    return pd.read_csv(PROCESSED_DIR / f"{name}.csv", dtype=str, keep_default_na=False)


def dashboard_payload() -> dict:
    fact, geo, ind, series = _read("FactObservation"), _read("DimGeography"), _read("DimIndicator"), _read("DimSeries")
    with open(RAW_DIR / "manifest.json", encoding="utf-8") as f:
        snapshot = json.load(f)["fetched_at_utc"][:10]
    geo_by_key = geo.set_index("GeographyKey")["GeographyCode"].to_dict()
    ind_by_key = ind.set_index("IndicatorKey")["IndicatorCode"].to_dict()
    meta = series.set_index("SeriesKey")
    out_series = {}
    for key, g in fact.groupby("SeriesKey", sort=True):
        g = g.sort_values("Date")
        code = ind_by_key[g["IndicatorKey"].iloc[0]]
        geo_code = geo_by_key[g["GeographyKey"].iloc[0]]
        out_series[f"{code}|{geo_code}"] = {
            "vector": meta.loc[key, "VectorLabel"],
            "table": meta.loc[key, "TableId"],
            "dates": g["Date"].tolist(),
            "values": [float(v) for v in g["Value"]],
            "status": [s for s in g["Status"]] if (g["Status"] != "").any() else None,
        }
    return {
        "snapshot": snapshot,
        "geographies": [
            {"code": r.GeographyCode, "name": r.GeographyName, "short": r.ShortName, "level": r.GeographyLevel,
             "sort": int(r.SortOrder), "colour": r.ColourHex, "colourDark": r.ColourHexDark}
            for r in geo.sort_values("SortOrder", key=lambda s: s.astype(int)).itertuples()
        ],
        "indicators": [
            {"code": r.IndicatorCode, "name": r.IndicatorName, "short": r.ShortName, "topic": r.Topic,
             "unit": r.Unit, "frequency": r.Frequency, "adjustment": r.Adjustment, "statistic": r.Statistic,
             "aggregation": r.AggregationMethod, "changeType": r.ChangeType, "direction": r.Direction,
             "decimals": int(r.Decimals), "format": r.FormatString, "stdErrCode": r.StdErrCode or None,
             "stdErrYoYCode": r.StdErrYoYCode or None, "referenceDay": r.ReferenceDay or None,
             "description": r.Description}
            for r in ind.sort_values("SortOrder", key=lambda s: s.astype(int)).itertuples()
        ],
        "tables": sorted({(r.TableId, r.TableTitle, r.TableUrl) for r in series.itertuples()}),
        "series": out_series,
    }


def _write_js(path: Path, global_name: str, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    path.write_text(f"// Generated by python -m stjohns_econ design. Do not edit.\n"
                    f"window.{global_name} = {body};\n", encoding="utf-8")


def run_web_data(out_dir: Path = WEB_DATA_DIR) -> list[Path]:
    dashboard, spec = out_dir / "dashboard.js", out_dir / "report-spec.js"
    _write_js(dashboard, "DASHBOARD", dashboard_payload())
    _write_js(spec, "REPORT_SPEC", rs.to_json())
    return [dashboard, spec]
